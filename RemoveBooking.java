    private void btnViewActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnViewActionPerformed
        // TODO add your handling code here:
        String bookingID = txtBookingID.getText().trim();
        Booking booking = manager.getBooking(bookingID);
        if (booking!= null) {
            txtRemoveBookingDisplay.setText(booking.toString());
        }else {
            txtRemoveBookingDisplay.setText("Booking Not Found");
        }
    }//GEN-LAST:event_btnViewActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        String bookingID = txtBookingID.getText();
        manager.deleteBooking(bookingID);
        JOptionPane.showMessageDialog(this, "Booking Deleted From System");
    }//GEN-LAST:event_btnDeleteActionPerformed

