    private void btnViewActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnViewActionPerformed
        // TODO add your handling code here:
        if (manager != null) {
            ArrayList<Cubicle> cubicles = manager.getAllCubicles();
            if (cubicles != null && !cubicles.isEmpty()) {
                StringBuilder sb = new StringBuilder();
                for (Cubicle cubicle : cubicles) {
                    sb.append(cubicle.toString()).append("\n");
                }
                txtAllCubicles.setText(sb.toString());
            }else {
                txtAllCubicles.setText("No Cubicles Found");
            }
        }else {
            txtAllCubicles.setText("Error: Manager is not initialised");
        }
    }//GEN-LAST:event_btnViewActionPerformed

