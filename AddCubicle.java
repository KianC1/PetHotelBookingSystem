    private void btnAddCubicleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddCubicleActionPerformed
        // TODO add your handling code here:
        String cubicleID = txtCubicleID.getText();
        String size = txtSize.getText();
        int floor = Integer.parseInt(txtFloor.getText());
        double cost = Double.parseDouble(txtCost.getText());
        boolean occupied = (cmbOccupied.getSelectedItem().equals("True"));
        
        Cubicle cubicles = new Cubicle(cubicleID, size, floor, cost, occupied);
        
        manager.addCubicle(cubicles);
        JOptionPane.showMessageDialog(this, "Successfully Added Cubicle");
    }//GEN-LAST:event_btnAddCubicleActionPerformed

