    private void btnViewActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnViewActionPerformed
// Ensure manager is initialized
    if (manager != null) {
        // Retrieve the ArrayList of Pet objects
        ArrayList<Pet> pets = manager.showAllPets();
        if (pets != null && !pets.isEmpty()) {
            // Format pet data for display
            StringBuilder sb = new StringBuilder();
            for (Pet pet : pets) {
                sb.append(pet.toString()).append("\n"); // New line for readability
            }
            txtAllPets.setText(sb.toString());
        } else {
            txtAllPets.setText("No Pets Found");
        }
    } else {
        txtAllPets.setText("Error: Manager is not initialised");
    }
    }//GEN-LAST:event_btnViewActionPerformed

