    private void btnViewSpecificPetActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnViewSpecificPetActionPerformed
        // Button to lookup the specific pet using its ID
        String petID = txtIDLookup.getText().trim();
        Pet pet = manager.getPet(petID);
        if (pet!=null) {
            txtSpecificPet.setText(pet.toString());
        }else{
            txtSpecificPet.setText("Pet Not Found");
        }
    }//GEN-LAST:event_btnViewSpecificPetActionPerformed

