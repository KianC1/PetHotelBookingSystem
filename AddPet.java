    private void btnAddRabbitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddRabbitActionPerformed
        // TODO add your handling code here:
        String petID = txtPetID.getText();
        String ownerName = txtOwnerName.getText();
        String telephone = txtTelephone.getText();
        String address = txtAddress.getText();
        int petAge = Integer.parseInt(txtAge.getText());
        boolean carrots = (cmbCarrots.getSelectedItem().equals("True"));
        boolean lettuce = (cmbLettuce.getSelectedItem().equals("True"));
    
        Rabbit pets = new Rabbit(petID, ownerName, telephone, address, petAge, carrots, lettuce);
        
        manager.addPet(pets);
        JOptionPane.showMessageDialog(this, "Successfully Added Pet!");
    }//GEN-LAST:event_btnAddRabbitActionPerformed

